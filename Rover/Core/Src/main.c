/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_UART4_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_TIM5_Init();
  MX_TIM8_Init();
  MX_TIM9_Init();
  MX_TIM10_Init();
  MX_TIM11_Init();
  MX_TIM12_Init();
  MX_TIM13_Init();
  MX_TIM14_Init();
  /* USER CODE BEGIN 2 */
  HAL_UART_Receive_IT(&huart4, &rx_byte, 1);
  
  for (int i = 0; i < 6; i++) {
      PID_Init(&pid_controllers[i], 2.0f, 0.5f, 0.01f, -8999.0f, 8999.0f);
  }
  
  HAL_TIM_Encoder_Start(&htim1, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim2, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim3, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim4, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim5, TIM_CHANNEL_ALL);
  HAL_TIM_Encoder_Start(&htim8, TIM_CHANNEL_ALL);
  
  HAL_TIM_PWM_Start(&htim9, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim10, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim11, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim12, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim13, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim14, TIM_CHANNEL_1);
  
  uint32_t last_tx_tick = HAL_GetTick();
  TxPacket tx_packet;
  tx_packet.header = 0xBBBB;
  for (int i = 0; i < 6; i++) {
      tx_packet.encoders[i] = 0;
  }
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    if (HAL_GetTick() - last_tx_tick >= 20) { // 50 Гц (20 мс)
        last_tx_tick += 20;
        
        // Failsafe проверка: если данных не было > 500 мс
        if (HAL_GetTick() - last_packet_time > 500) {
            for (int i = 0; i < 6; i++) {
                target_speed[i] = 0.0f;
            }
            HAL_GPIO_WritePin(LD1_GPIO_Port, LD1_Pin, GPIO_PIN_RESET); // Зеленый ВЫКЛ
            HAL_GPIO_WritePin(LD3_GPIO_Port, LD3_Pin, GPIO_PIN_SET);   // Красный ВКЛ
        }
        
        read_encoders();
        
        // Константы для перевода тиков энкодера в м/с
        const float GEAR_RATIO = 46.0f;     // Передаточное число редуктора 1:46
        const float ENCODER_CPR = 44.0f;    // 11 PPR * 4 (счет по обоим фронтам)
        const float WHEEL_DIAMETER = 0.10f; // Колесо 100 мм (0.1 м)
        const float PI = 3.1415926f;
        const float METERS_PER_TICK = (PI * WHEEL_DIAMETER) / (GEAR_RATIO * ENCODER_CPR);

        float motor_outputs[6];
        for (int i = 0; i < 6; i++) {
            tx_packet.encoders[i] += current_speeds[i];
            
            // Переводим скорость из "тиков за 20мс" в "метры в секунду"
            float current_speed_ms = (current_speeds[i] / 0.02f) * METERS_PER_TICK;
            
            motor_outputs[i] = target_speed[i] * (float)MAX_PWM;
        }
        
        apply_motor_power(motor_outputs);
        
        // Считаем CRC-8 от данных без байта CRC
        tx_packet.crc = calculate_crc8((uint8_t*)&tx_packet, sizeof(TxPacket) - 1);
        
        // Отправляем пакет по UART4 через DMA
        if (huart4.gState == HAL_UART_STATE_READY) {
            HAL_UART_Transmit_DMA(&huart4, (uint8_t*)&tx_packet, sizeof(TxPacket));
        }
    }
  }
  /* USER CODE END 3 */
}

